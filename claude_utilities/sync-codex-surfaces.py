#!/usr/bin/env python3
"""Generate Codex agents and skills from this repository's Claude surfaces."""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import sys


MODEL_MAP = {
    "opus": ("gpt-6-astra", "high"),
    "fable": ("gpt-6-astra", "high"),
    "sonnet": ("gpt-5.6-terra", "medium"),
    "haiku": ("gpt-5.6-luna", "low"),
}
GENERATED_MARKER = "Generated by claude_utilities/sync-codex-surfaces.py"


def parse_frontmatter(path: Path) -> tuple[dict[str, str], str]:
    text = path.read_text(encoding="utf-8")
    match = re.match(r"\A---\s*\n(.*?)\n---\s*\n?", text, re.DOTALL)
    if not match:
        raise ValueError(f"{path}: expected YAML frontmatter")

    metadata: dict[str, str] = {}
    for line in match.group(1).splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        key, separator, value = line.partition(":")
        if not separator:
            raise ValueError(f"{path}: unsupported frontmatter line: {line!r}")
        metadata[key.strip()] = value.strip().strip('"').strip("'")
    return metadata, text[match.end() :]


def toml_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def toml_instructions(body: str) -> str:
    body = body.rstrip() + "\n"
    if "'''" in body:
        return toml_string(body)
    return "'''\n" + body + "'''"


def adapt_for_codex(text: str) -> str:
    """Translate Claude-specific runtime vocabulary without changing source files."""
    replacements = (
        (
            "passing `run_in_background: true` to the Agent tool",
            "spawning independent subagents",
        ),
        ("background agents work", "subagents work"),
        ("Background agents are tied", "Subagents are tied"),
        ("Claude Code", "Codex"),
        ("closes Claude", "closes Codex"),
        ("A future Claude", "A future Codex agent"),
        ("Fable variant", "Astra variant"),
        ("Claude Fable 5", "GPT-6 Astra"),
        ("`WebSearch`", "web search"),
        ("WebSearch", "web search"),
        ("`WebFetch`", "page retrieval"),
        ("WebFetch", "page retrieval"),
        ("(Opus)", "(GPT-6 Astra)"),
        ("(Sonnet)", "(GPT-5.6 Terra)"),
        (", opus)", ", GPT-6 Astra)"),
        (", sonnet)", ", GPT-5.6 Terra)"),
    )
    for old, new in replacements:
        text = text.replace(old, new)
    return text


def write_generated(path: Path, content: str) -> None:
    if path.exists() and GENERATED_MARKER not in path.read_text(encoding="utf-8"):
        raise FileExistsError(f"refusing to overwrite non-generated file: {path}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def convert_agents(root: Path) -> int:
    source_dir = root / ".claude" / "agents"
    destination_dir = root / ".codex" / "agents"
    if not source_dir.is_dir():
        raise FileNotFoundError(f"Claude agent directory not found: {source_dir}")

    count = 0
    for source in sorted(source_dir.glob("*.md")):
        metadata, body = parse_frontmatter(source)
        name = metadata.get("name")
        description = metadata.get("description")
        if not name or not description:
            raise ValueError(f"{source}: agent requires name and description")
        description = adapt_for_codex(description)
        body = adapt_for_codex(body)

        lines = [
            f"# {GENERATED_MARKER}; edit {source.relative_to(root)} instead.",
            f"name = {toml_string(name)}",
            f"description = {toml_string(description)}",
        ]
        claude_model = metadata.get("model")
        if claude_model:
            if claude_model not in MODEL_MAP:
                raise ValueError(f"{source}: no Codex model mapping for {claude_model!r}")
            model, default_effort = MODEL_MAP[claude_model]
            lines.append(f"model = {toml_string(model)}")
            effort = metadata.get("effort", default_effort)
            lines.append(f"model_reasoning_effort = {toml_string(effort)}")
        elif metadata.get("effort"):
            lines.append(f"model_reasoning_effort = {toml_string(metadata['effort'])}")
        lines.extend(["", f"developer_instructions = {toml_instructions(body)}", ""])

        write_generated(destination_dir / f"{source.stem}.toml", "\n".join(lines))
        count += 1
    return count


def convert_commands(root: Path) -> int:
    source_dir = root / ".claude" / "commands"
    if not source_dir.is_dir():
        return 0

    count = 0
    for source in sorted(source_dir.glob("*.md")):
        metadata, body = parse_frontmatter(source)
        name = metadata.get("name", source.stem)
        description = metadata.get("description")
        if not description:
            raise ValueError(f"{source}: command requires a description")
        content = (
            "---\n"
            f"name: {name}\n"
            f"description: {description}\n"
            "---\n\n"
            f"<!-- {GENERATED_MARKER}; edit {source.relative_to(root)} instead. -->\n\n"
            + body.lstrip()
        )
        write_generated(root / ".claude" / "skills" / name / "SKILL.md", content)
        count += 1
    return count


def link_skills(root: Path) -> None:
    agents_dir = root / ".agents"
    link = agents_dir / "skills"
    target = Path("../.claude/skills")
    agents_dir.mkdir(parents=True, exist_ok=True)

    if link.is_symlink():
        if Path(os.readlink(link)) == target:
            return
        link.unlink()
    elif link.exists():
        raise FileExistsError(f"refusing to replace non-symlink path: {link}")
    link.symlink_to(target)


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Convert .claude agents/commands for Codex and link shared skills."
    )
    parser.add_argument("project", nargs="?", default=".", type=Path)
    args = parser.parse_args()
    root = args.project.expanduser().resolve()

    try:
        agent_count = convert_agents(root)
        command_count = convert_commands(root)
        link_skills(root)
    except (FileExistsError, FileNotFoundError, ValueError) as error:
        print(f"Error: {error}", file=sys.stderr)
        return 1

    print(
        f"Codex surfaces synchronized: {agent_count} agents, "
        f"{command_count} command skills, shared skills link"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
